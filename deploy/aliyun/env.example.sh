# ---------------- 服务器连接 ----------------
SERVER_IP="121.43.150.109"          # 阿里云公网 IP
SERVER_USER="root"                  # 有 sudo 权限的用户
SSH_PORT="22"
SSH_KEY="$HOME/.ssh/id_rsa"         # 本机私钥路径（Windows: C:/Users/xxx/.ssh/id_rsa）
REMOTE_ROOT="/opt/pdk"              # 服务器上的安装根目录

# ---------------- 访问地址 ----------------
# 客户端升级系统会用这个地址下发下载地址，必须是客户端能访问到的地址。
# 先用 IP 访问就保持下面这样；以后换成域名，改这里重新跑一次 02 即可。
PDK_PUBLIC_BASE_URL="http://121.43.150.109"
PDK_SERVER_NAME="121.43.150.109"    # Nginx 的 server_name，可填域名（空格分隔多个）
SERVER_PORT="8080"                  # 后端监听端口（Nginx 反代到它，不建议改）

# ---------------- 管理员初始密码 ----------------
# 摘要算法 = SHA256(pepper + ":" + 密码)，pepper 每次全新部署都会随机生成，
# 所以 schema 里写死的那个摘要在生产环境是登不进去的，必须由部署脚本重算。
# 留空 = 自动生成随机密码（更推荐，密码会打印在终端并存到服务器 /opt/pdk/.admin-init-password）
ADMIN_INIT_PASSWORD=""

# ---------------- JVM 内存 ----------------
# 建议设为服务器物理内存的 50%~60%（后端 + MySQL + Redis + Nginx 共存）
#   2GB 内存 -> 512m      4GB 内存 -> 1536m      8GB 内存 -> 3g
JAVA_XMX="768m"

# ---------------- 可选：跳过已完成的初始化 ----------------
# 服务器环境已装好时设为 yes，可省去重复的 apt 安装（快很多）
SKIP_PREPARE="no"
